"""Prepare two fixed TUM RGB-D subsets without releasing original images.

Controlled blur is generated by independent depth-based z-buffered bilinear
point reprojection of real images, not by the Gaussian renderer under test.
"""
import argparse
import hashlib
import json
import tarfile
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import binary_erosion
from scipy.spatial.transform import Rotation,Slerp
from scipy.spatial import cKDTree

BASE='https://cvg.cit.tum.de/rgbd/dataset/freiburg1/'
SEQUENCES=['freiburg1_xyz','freiburg1_desk']


def digest(path):
    h=hashlib.sha256()
    with open(path,'rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()


def table(content):
    return [line.split() for line in content.decode().splitlines() if line.strip() and not line.startswith('#')]


def reproject(rgb,depth,K,translation,rotation):
    """World=current camera; input rotation is target camera-to-world."""
    height,width=depth.shape;fx,fy,cx,cy=K
    yy,xx=np.mgrid[:height,:width]
    xyz=np.stack([(xx-cx)*depth/fx,(yy-cy)*depth/fy,depth],-1)
    valid=(depth>.2)&(depth<5.)
    point=(xyz[valid]-translation)@rotation
    color=rgb[valid]
    z=point[:,2];ok=z>.1;point=point[ok];color=color[ok];z=z[ok]
    u=point[:,0]/z*fx+cx;v=point[:,1]/z*fy+cy
    x0=np.floor(u).astype(int);y0=np.floor(v).astype(int)
    indices=[];weights=[];depths=[];colors=[]
    for dx,dy in [(0,0),(1,0),(0,1),(1,1)]:
        x=x0+dx;y=y0+dy
        weight=(1-abs(u-x))*(1-abs(v-y))
        keep=(x>=0)&(x<width)&(y>=0)&(y<height)&(weight>1e-6)
        indices.append(y[keep]*width+x[keep]);weights.append(weight[keep]);depths.append(z[keep]);colors.append(color[keep])
    idx=np.concatenate(indices);w=np.concatenate(weights);zz=np.concatenate(depths);cc=np.concatenate(colors)
    nearest=np.full(height*width,np.inf);np.minimum.at(nearest,idx,zz)
    keep=zz<=nearest[idx]+.01+.005*zz
    idx=idx[keep];w=w[keep];cc=cc[keep]
    denom=np.bincount(idx,weights=w,minlength=height*width)
    out=np.stack([np.bincount(idx,weights=w*cc[:,j],minlength=height*width) for j in range(3)],-1)
    out=out/np.maximum(denom[:,None],1e-12)
    return out.reshape(height,width,3),denom.reshape(height,width)>.2


def resize_float(image,size):
    if image.ndim==3:
        return np.stack([np.asarray(Image.fromarray(image[...,j].astype('float32')).resize(size,Image.Resampling.BOX)) for j in range(3)],-1)
    return np.asarray(Image.fromarray(image.astype('float32')).resize(size,Image.Resampling.BOX))


def prepare(sequence,width=96,height=72,blur_samples=32):
    archive=Path(f'data/downloads/{sequence}.tgz')
    out=Path('data/prepared');out.mkdir(parents=True,exist_ok=True)
    prefix='rgbd_dataset_'+sequence+'/'
    sources=[]
    with tarfile.open(archive,'r:gz') as tf:
        def read(name):
            body=tf.extractfile(prefix+name).read()
            sources.append({'path':prefix+name,'sha256':hashlib.sha256(body).hexdigest()})
            return body
        rgb_rows=table(read('rgb.txt'));depth_rows=table(read('depth.txt'));gt=np.array(table(read('groundtruth.txt')),dtype=float)
        rgb_times=np.array([float(x[0]) for x in rgb_rows]);depth_times=np.array([float(x[0]) for x in depth_rows])
        start=int(np.searchsorted(rgb_times,rgb_times[0]+5.))
        chosen=np.arange(start,start+45,3)
        assert chosen[-1]<len(rgb_rows)
        rotations=Rotation.from_quat(gt[:,4:8]);slerp=Slerp(gt[:,0],rotations)
        def pose(t):
            center=np.array([np.interp(t,gt[:,0],gt[:,j]) for j in range(1,4)])
            return center,slerp(t).as_matrix()
        images=[];blurry=[];depths=[];masks=[];controlled_masks=[];centers=[];Rs=[];vs=[];ws=[];frames=[]
        import io
        for frame_id,rgb_index in enumerate(chosen):
            t=rgb_times[rgb_index];di=int(abs(depth_times-t).argmin())
            assert abs(depth_times[di]-t)<.02
            assert gt[0,0]+.06<t<gt[-1,0]-.06
            rgb=Image.open(io.BytesIO(read(rgb_rows[rgb_index][1]))).convert('RGB')
            dep=Image.open(io.BytesIO(read(depth_rows[di][1])))
            base_rgb=np.asarray(rgb.resize((320,240),Image.Resampling.BOX),dtype=np.float64)/255
            base_depth=np.asarray(dep.resize((320,240),Image.Resampling.NEAREST),dtype=np.float64)/5000
            baseK=np.array([262.5,262.5,159.5,119.5])
            center,R=pose(t);cm,Rm=pose(t-.05);cp,Rp=pose(t+.05)
            velocity=R.T@(cp-cm)/.1
            omega=(Rotation.from_matrix(R.T@Rp).as_rotvec()-Rotation.from_matrix(R.T@Rm).as_rotvec())/.1
            exposure=.08
            integrated=np.zeros_like(base_rgb);valid=np.ones((240,320),dtype=bool)
            for j in range(blur_samples):
                tau=((j+.5)/blur_samples-.5)*exposure
                # Local constant body twist around actual frame pose. Translation
                # is linear; rotation is exp(omega*tau), matching declared camera model.
                warped,ok=reproject(base_rgb,base_depth,baseK,velocity*tau,Rotation.from_rotvec(omega*tau).as_matrix())
                integrated+=warped/blur_samples;valid&=ok
            rgb_small=resize_float(base_rgb,(width,height))
            blur_small=resize_float(integrated,(width,height))
            depth_small=np.asarray(dep.resize((width,height),Image.Resampling.NEAREST),dtype=np.float32)/5000
            mask=(depth_small>.2)&(depth_small<5.)
            strict=resize_float(valid.astype(float),(width,height))>.999
            strict=binary_erosion(strict&mask,iterations=1)
            images.append(rgb_small);blurry.append(blur_small);depths.append(depth_small);masks.append(mask);controlled_masks.append(strict)
            centers.append(center);Rs.append(R.T);vs.append(velocity);ws.append(omega)
            frames.append({'frame_id':frame_id,'rgb_index':int(rgb_index),'timestamp':t,'rgb':rgb_rows[rgb_index][1],
                           'depth':depth_rows[di][1],'depth_timestamp':float(depth_times[di]),'rgb_depth_dt':float(depth_times[di]-t),
                           'native_valid_fraction':float(mask.mean()),'controlled_valid_fraction':float(strict.mean()),
                           'local_linear_velocity':velocity.tolist(),'local_angular_velocity':omega.tolist()})
            print(sequence,frame_id,'valid',round(float(strict.mean()),3),flush=True)
    rgb=np.array(images,dtype='float32');blur=np.array(blurry,dtype='float32');depth=np.array(depths,dtype='float32')
    centers=np.array(centers,dtype='float32');Rs=np.array(Rs,dtype='float32')
    test=np.array([2,5,8,11,14]);train=np.array([i for i in range(15) if i not in test])
    K=np.array([525*width/640,525*height/480,(319.5+.5)*width/640-.5,(239.5+.5)*height/480-.5],dtype='float32')
    # Fuse ONLY training RGB-D geometry. Colors are fused from the appropriate
    # observation track later: controlled blur never receives clean RGB colors.
    points=[];scales=[];image_ids=[];pixel_ids=[]
    yy,xx=np.mgrid[:height,:width]
    for i in train:
        valid=masks[i];z=depth[i][valid]
        cam=np.stack([(xx[valid]-K[2])*z/K[0],(yy[valid]-K[3])*z/K[1],z],-1)
        world=cam@Rs[i]+centers[i]
        points.append(world);scales.append(z/K[0]*.8)
        image_ids.extend([i]*len(z));pixel_ids.extend(np.flatnonzero(valid))
    point=np.concatenate(points);scale=np.concatenate(scales)
    voxel=np.floor(point/.025).astype(np.int64)
    unique,inverse=np.unique(voxel,axis=0,return_inverse=True)
    counts=np.bincount(inverse)
    mean=np.stack([np.bincount(inverse,weights=point[:,j])/counts for j in range(3)],-1)
    scale=np.bincount(inverse,weights=scale)/counts
    rng=np.random.default_rng(20261117)
    selected=np.sort(rng.choice(len(mean),min(2400,len(mean)),replace=False))
    group_map=np.full(len(mean),-1);group_map[selected]=np.arange(len(selected));groups=group_map[inverse]
    init_mean=mean[selected].astype('float32')
    spacing=cKDTree(init_mean).query(init_mean,k=2)[0][:,1]
    init_scale=np.maximum(scale[selected],np.minimum(.8*spacing,.05)).astype('float32')
    valid=groups>=0
    save=dict(rgb=rgb,blur=blur,depth=depth,native_mask=np.array(masks),controlled_mask=np.array(controlled_masks),
              centers=centers,rotations=Rs,velocities=np.array(vs,dtype='float32'),omegas=np.array(ws,dtype='float32'),
              intrinsics=K,train=train,test=test,init_means=init_mean,init_scale=init_scale,
              fusion_groups=groups[valid],fusion_images=np.array(image_ids)[valid],fusion_pixels=np.array(pixel_ids)[valid])
    path=out/f'{sequence}.npz';np.savez_compressed(path,**save)
    meta={'sequence':sequence,'url':BASE+'rgbd_dataset_'+sequence+'.tgz','archive_sha256':digest(archive),
          'archive_bytes':archive.stat().st_size,'prepared_sha256':digest(path),'reviewed':'2026-11-17','resolution':[width,height],
          'frames':frames,'train':train.tolist(),'test':test.tolist(),'gaussians':len(init_mean),'voxel_size_m':.025,
          'max_gaussians':2400,'initial_sigma':'max(0.8 pixel projected world scale, min(0.8 nearest selected-point spacing, 0.05m))',
          'sources':sources,'calibration':'ROS default525/525/319.5/239.5; no undistortion, as recommended by TUM for pre-registered RGB-D',
          'depth_divisor':5000,'additional_depth_scale':1.,'depth_already_corrected':True,'rgb_resize':'BOX via320x240','depth_resize':'NEAREST',
          'pose':'interpolated mocap camera-to-world; linear position + quaternion SLERP','velocity_dt_seconds':.05,
          'controlled_exposure_seconds':.08,'controlled_samples':blur_samples,'controlled_renderer':'independent bilinear point reprojection with nearest-surface z-buffer',
          'controlled_limit':'Existing native image blur is retained; this is additional controlled blur on real RGB-D, not sensor clean GT.',
          'initialization':'Training depth only for geometry; colors from respective training observation track, never held-out frames',
          'publication':'Original/processed RGB-D arrays are local ignored caches, not committed or uploaded.'}
    Path(f'results/phase2/{sequence}_source.json').write_text(json.dumps(meta,indent=2))
    return meta


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--sequences',nargs='+',choices=SEQUENCES,default=SEQUENCES)
    p.add_argument('--samples',type=int,default=32);a=p.parse_args()
    for seq in a.sequences:prepare(seq,blur_samples=a.samples)
